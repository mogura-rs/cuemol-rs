use cuemol_molstr::{
    parse_selector, read_mmcif_file, read_pdb_file, read_pdb_str, write_pdb_string, MolCoord,
};
use std::path::PathBuf;

#[test]
fn pdb_writer_roundtrips_reference_fixture_shape() {
    let Some(root) = reference_test_data_root() else {
        return;
    };

    let mol = read_pdb_file(root.join("1CRN.pdb")).unwrap();
    let output = write_pdb_string(&mol);
    let lines = output.lines().collect::<Vec<_>>();
    assert_eq!(lines[0], "REMARK   PDB File Generated by CueMol2");
    assert!(lines
        .iter()
        .any(|line| line.starts_with("SSBOND   1 CYS A   3")));
    let first_atom = lines
        .iter()
        .position(|line| line.starts_with("ATOM"))
        .unwrap();
    assert!(lines[first_atom].starts_with("ATOM      1  N   THR A   1"));
    assert!(lines[first_atom + 1].starts_with("ATOM      2  CA  THR A   1"));
    assert_eq!(lines[lines.len() - 2], "TER");
    assert_eq!(lines[lines.len() - 1], "END");

    let roundtrip = read_pdb_str(&output).unwrap();
    assert_eq!(roundtrip.atom_count(), 327);
    assert_eq!(roundtrip.residue_count(), 46);
    assert_eq!(roundtrip.chain_ids(), vec!["A"]);
    let first = &roundtrip.atoms()[0];
    assert_eq!(first.name, "N");
    assert_eq!(first.res_name, "THR");
    assert!((first.position.x - 17.047).abs() < 1.0e-5);
    assert!((first.occupancy - 1.0).abs() < 1.0e-6);
    assert!((first.b_factor - 13.79).abs() < 1.0e-5);
}

#[test]
fn delete_selected_atoms_remaps_remaining_bonds() {
    let Some(root) = reference_test_data_root() else {
        return;
    };

    let mut mol = read_mmcif_file(root.join("1crn.cif")).unwrap();
    let selector = parse_selector("name CA").unwrap();
    let before_bonds = mol.bond_count();
    let deleted = mol.delete_selected_atoms(&selector);

    assert_eq!(deleted, 46);
    assert_eq!(mol.atom_count(), 281);
    assert!(mol.bond_count() < before_bonds);
    assert!(mol
        .bonds()
        .iter()
        .all(|bond| bond.atom1 < mol.atom_count() && bond.atom2 < mol.atom_count()));
    assert!(mol
        .atoms()
        .iter()
        .all(|atom| !atom.name.trim().eq_ignore_ascii_case("CA")));
}

#[test]
fn copy_selected_atoms_copies_atoms_and_internal_bonds() {
    let Some(root) = reference_test_data_root() else {
        return;
    };

    let source = read_mmcif_file(root.join("1crn.cif")).unwrap();
    let selector = parse_selector("chain A and resi 1").unwrap();
    let mut target = MolCoord::new();
    let copied = target.copy_selected_atoms_from(&source, &selector).unwrap();

    assert_eq!(copied, 7);
    assert_eq!(target.atom_count(), 7);
    assert!(target.bond_count() > 0);
    assert!(target.atoms().iter().all(|atom| atom.chain_id == "A"));
    assert!(target.atoms().iter().all(|atom| atom.res_id == 1));
}

#[test]
fn copy_selected_atoms_rejects_residue_collision_without_mutating() {
    let Some(root) = reference_test_data_root() else {
        return;
    };

    let source = read_mmcif_file(root.join("1crn.cif")).unwrap();
    let selector = parse_selector("chain A and resi 1").unwrap();
    let mut target = MolCoord::new();
    target.copy_selected_atoms_from(&source, &selector).unwrap();
    let atom_count = target.atom_count();
    let bond_count = target.bond_count();

    assert!(target.copy_selected_atoms_from(&source, &selector).is_err());
    assert_eq!(target.atom_count(), atom_count);
    assert_eq!(target.bond_count(), bond_count);
}

fn reference_test_data_root() -> Option<PathBuf> {
    let root = option_env!("CUEMOL2_REF_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../../cuemol2"));
    let path = root.join("tests/test_data");
    path.exists().then_some(path)
}
