use cuemol_molstr::read_xplor_map_with_header_str;

#[test]
fn xplor_map_reader_reads_minimal_density_map() {
    let map = read_xplor_map_with_header_str(&xplor_map([2, 1, 1], [0, 0, 0], [1.0, 2.0])).unwrap();

    assert_eq!(map.grid.counts, [2, 1, 1]);
    assert_eq!(map.header.start, [0, 0, 0]);
    assert_eq!(map.header.end, [1, 0, 0]);
    assert_eq!(map.grid.values, vec![1.0, 2.0]);
    assert_eq!(map.header.title_count, 1);
    assert!((map.grid.delta[0].x - 1.0).abs() < 1.0e-6);
}

#[test]
fn xplor_map_reader_accepts_start_based_section_number() {
    let map = read_xplor_map_with_header_str(&xplor_map([1, 1, 1], [3, 0, 2], [7.0])).unwrap();

    assert_eq!(map.grid.counts, [1, 1, 1]);
    assert_eq!(map.header.start, [3, 0, 2]);
    assert_eq!(map.grid.values, vec![7.0]);
}

fn xplor_map(counts: [i32; 3], start: [i32; 3], values: impl IntoIterator<Item = f64>) -> String {
    let end = [
        start[0] + counts[0] - 1,
        start[1] + counts[1] - 1,
        start[2] + counts[2] - 1,
    ];
    let section_number = start[2];
    let mut output = String::new();
    output.push('\n');
    output.push_str("       1\n");
    output.push_str(" REMARKS generated by test\n");
    output.push_str(&format!(
        "{:8}{:8}{:8}{:8}{:8}{:8}{:8}{:8}{:8}\n",
        counts[0], start[0], end[0], counts[1], start[1], end[1], counts[2], start[2], end[2]
    ));
    output.push_str(&format!(
        "{:12.5E}{:12.5E}{:12.5E}{:12.5E}{:12.5E}{:12.5E}\n",
        2.0, 1.0, 1.0, 90.0, 90.0, 90.0
    ));
    output.push_str("ZYX\n");
    output.push_str(&format!("{section_number}\n"));
    for (index, value) in values.into_iter().enumerate() {
        output.push_str(&format!("{value:12.5E}"));
        if index % 6 == 5 {
            output.push('\n');
        }
    }
    output.push('\n');
    output
}
