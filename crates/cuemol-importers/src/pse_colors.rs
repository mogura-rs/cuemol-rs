pub(crate) fn pse_color(index: i64) -> Option<u32> {
    let index = usize::try_from(index).ok()?;
    pse_colors().get(index).copied()
}

fn pse_colors() -> &'static [u32] {
    static COLORS: OnceLock<Box<[u32]>> = OnceLock::new();
    COLORS
        .get_or_init(|| {
            let bytes = decode_base64(PSE_COLORS_BASE64);
            debug_assert_eq!(bytes.len(), 5386 * 4);
            bytes
                .chunks_exact(4)
                .map(|chunk| u32::from_be_bytes([chunk[0], chunk[1], chunk[2], chunk[3]]))
                .collect::<Vec<_>>()
                .into_boxed_slice()
        })
        .as_ref()
}

fn decode_base64(input: &str) -> Vec<u8> {
    let mut output = Vec::with_capacity(input.len() / 4 * 3);
    let mut accumulator = 0_u32;
    let mut bit_count = 0_u8;
    for byte in input.bytes() {
        if byte == b'=' {
            break;
        }
        let value = match byte {
            b'A'..=b'Z' => byte - b'A',
            b'a'..=b'z' => byte - b'a' + 26,
            b'0'..=b'9' => byte - b'0' + 52,
            b'+' => 62,
            b'/' => 63,
            _ => continue,
        };
        accumulator = (accumulator << 6) | u32::from(value);
        bit_count += 6;
        if bit_count >= 8 {
            bit_count -= 8;
            output.push((accumulator >> bit_count) as u8);
            accumulator &= if bit_count == 0 {
                0
            } else {
                (1_u32 << bit_count) - 1
            };
        }
    }
    output
}

